const DICTS: Record<UiLanguage, Dict> = { es, fr, pt, ja, en };

export function detectUiLanguage(): UiLanguage {
  const stored = localStorage.getItem('lexo.ui');
  if (stored && stored in DICTS) return stored as UiLanguage;
  for (const tag of navigator.languages ?? [navigator.language]) {
    const base = tag.slice(0, 2).toLowerCase();
    if (base in DICTS) return base as UiLanguage;
  }
  return 'en';
}

/** Look a key up, falling back to English then to the key itself. */
export function translator(language: UiLanguage) {
  const dict = DICTS[language] ?? en;
  return (key: string): string => dict[key] ?? en[key] ?? key;
}

export type T = ReturnType<typeof translator>;
